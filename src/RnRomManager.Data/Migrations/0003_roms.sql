-- Spec §14.1 roms. region_key is pipe-delimited at both ends (`|USA|Europe|`) for LIKE '%|USA|%'.
CREATE TABLE roms (
    id                 BIGINT        NOT NULL AUTO_INCREMENT,
    game_id            CHAR(36)      NOT NULL,
    system_id          VARCHAR(16)   NOT NULL,
    file_name          VARCHAR(255)  NOT NULL,
    original_file_name VARCHAR(255)  NOT NULL,
    base_title         VARCHAR(255)  NOT NULL,
    regions            JSON          NOT NULL,
    languages          JSON          NOT NULL,
    flags              JSON          NOT NULL,
    region_key         VARCHAR(255)  NOT NULL,
    revision           VARCHAR(32)   NULL,
    is_primary         TINYINT(1)    NOT NULL DEFAULT 0,
    id_method          VARCHAR(16)   NOT NULL,
    dat_name           VARCHAR(255)  NULL,
    dat_version        VARCHAR(255)  NULL,
    dat_game_name      VARCHAR(255)  NULL,
    size_bytes         BIGINT        NOT NULL,
    crc32              CHAR(8)       NOT NULL,
    md5                CHAR(32)      NOT NULL,
    sha1               CHAR(40)      NOT NULL,
    header             JSON          NULL,
    date_added         DATETIME(6)   NOT NULL,
    date_modified      DATETIME(6)   NOT NULL,
    CONSTRAINT pk_roms PRIMARY KEY (id),
    CONSTRAINT ux_roms_sha1 UNIQUE (sha1),
    CONSTRAINT fk_roms_game FOREIGN KEY (game_id) REFERENCES games (id) ON DELETE CASCADE,
    INDEX ix_roms_game_id (game_id),
    INDEX ix_roms_system_base_title (system_id, base_title),
    INDEX ix_roms_crc32 (crc32)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
