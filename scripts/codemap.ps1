#!/usr/bin/env pwsh
# Generates docs/codemap.md: a compact, greppable index of the codebase (API routes, SPA pages, jobs, system handlers,
# migrations, source files per folder, tests, doc section line numbers) so agents can find code without sweeping the repo.
# Run after adding or moving routes, pages, jobs, files or doc sections: pwsh scripts/codemap.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
Set-Location $root

function Rel([string]$path) { [IO.Path]::GetRelativePath($root, $path).Replace('\', '/') }
function SourceFiles([string]$dir, [string[]]$include) {
    Get-ChildItem $dir -Recurse -File -Include $include |
        Where-Object { $_.FullName -notmatch '[\\/](bin|obj|node_modules|vendor|\.svelte-kit|build)[\\/]' } |
        Sort-Object FullName
}

$out = [Collections.Generic.List[string]]::new()
$out.Add('# Code map')
$out.Add('')
$out.Add('Generated by `scripts/codemap.ps1`; do not edit by hand. Read this before exploring; open only the files it points to.')
$out.Add('Rules and patterns for common changes: [recipes.md](recipes.md).')

# --- API routes ---------------------------------------------------------------------------------------------------
$out.Add(''); $out.Add('## API routes'); $out.Add('')
$out.Add('`METHOD /path` (Admin = AdminOnly on the group or route) — file:line. Groups hang off `/api` (AppHost).')
$out.Add('')
foreach ($file in SourceFiles 'src/RnRomManager.Api' '*.cs') {
    $lines = Get-Content $file.FullName
    $groups = @{ 'api' = @{ Prefix = '/api'; Admin = $false }; 'app' = @{ Prefix = ''; Admin = $false } }
    $rows = @()
    for ($i = 0; $i -lt $lines.Count; $i++) {
        $line = $lines[$i]
        if ($line -match '(?:var\s+)?(\w+)\s*=\s*(\w+)\.MapGroup\("([^"]*)"\)') {
            $name, $parentName, $prefix = $Matches[1], $Matches[2], $Matches[3]
            $parent = $groups[$parentName] ?? @{ Prefix = '/api'; Admin = $false }
            $groups[$name] = @{ Prefix = $parent.Prefix + $prefix; Admin = $parent.Admin -or $line.Contains('AdminOnly') }
        }
        if ($line -match '(\w+)\.Map(Get|Post|Put|Delete|Patch)\("([^"]*)"') {
            $groupName, $method, $route = $Matches[1], $Matches[2], $Matches[3]
            $group = $groups[$groupName] ?? @{ Prefix = '?'; Admin = $false }
            # The route's own RequireAuthorization usually sits on a later line, at the end of the lambda.
            $admin = $group.Admin
            for ($j = $i; $j -lt [Math]::Min($i + 80, $lines.Count); $j++) {
                if ($j -gt $i -and $lines[$j] -match '\.Map(Get|Post|Put|Delete|Patch)\(') { break }
                if ($lines[$j] -match 'AdminOnly') { $admin = $true; break }
            }
            $path = ($group.Prefix + $route).TrimEnd('/')
            $rows += '- `{0} {1}`{2} — {3}:{4}' -f $method.ToUpper(), $path, ($admin ? ' Admin' : ''), (Rel $file.FullName), ($i + 1)
        }
    }
    $rows | ForEach-Object { $out.Add($_) }
}

# --- SPA pages ----------------------------------------------------------------------------------------------------
$out.Add(''); $out.Add('## SPA pages'); $out.Add('')
$routes = 'src/RnRomManager.Web/src/routes'
foreach ($file in SourceFiles $routes '+page.svelte', '+layout.svelte') {
    $rel = [IO.Path]::GetRelativePath((Resolve-Path $routes), $file.DirectoryName).Replace('\', '/')
    $route = $rel -eq '.' ? '/' : "/$rel"
    $kind = $file.Name -eq '+layout.svelte' ? ' (layout)' : ''
    $out.Add(('- `{0}`{1} — {2}' -f $route, $kind, (Rel $file.FullName)))
}

# --- Jobs and system handlers -------------------------------------------------------------------------------------
$out.Add(''); $out.Add('## Jobs'); $out.Add('')
$jobText = Get-Content (Join-Path $root 'src/RnRomManager.Core/Jobs/Job.cs') -Raw
$jobEnum = [regex]::Match($jobText, 'enum JobType\s*\{([^}]*)\}').Groups[1].Value -replace '(?m)^\s*///.*$', ''
$jobTypes = ([regex]::Matches($jobEnum, '\w+') | ForEach-Object Value) -join ', '
$out.Add("``JobType``: $jobTypes (Core/Jobs/Job.cs; ``jobs.type`` is VARCHAR(16)). Implementations:")
# Primary constructors span lines, so match across the whole file.
foreach ($file in SourceFiles 'src' '*.cs') {
    $m = [regex]::Match((Get-Content $file.FullName -Raw), 'class (\w+)\b[^{;]*?:\s*IJob\b')
    if ($m.Success) { $out.Add(('- {0} — {1}' -f $m.Groups[1].Value, (Rel $file.FullName))) }
}
$out.Add(''); $out.Add('## System handlers'); $out.Add('')
foreach ($m in SourceFiles 'src' '*.cs' | Select-String -Pattern 'class (\w+)\b[^{]*:\s*[^{]*\bISystemHandler\b') {
    $hit = Select-String -Path $m.Path -Pattern 'string Id\s*=>\s*"([^"]+)"' | Select-Object -First 1
    $id = $hit ? $hit.Matches[0].Groups[1].Value : $null
    $out.Add(('- {0}{1} — {2}' -f $m.Matches[0].Groups[1].Value, ($id ? " ``$id``" : ''), (Rel $m.Path)))
}

# --- Migrations ---------------------------------------------------------------------------------------------------
$out.Add(''); $out.Add('## Migrations (src/RnRomManager.Data/Migrations)'); $out.Add('')
$out.Add((Get-ChildItem 'src/RnRomManager.Data/Migrations' -Filter *.sql | Sort-Object Name | ForEach-Object { $_.BaseName }) -join ', ')

# --- Source files per folder --------------------------------------------------------------------------------------
$out.Add(''); $out.Add('## Source files by folder'); $out.Add('')
$out.Add('File names without extension. System projects (`src/RnRomManager.Systems.*`) are omitted: one handler each, listed above.')
$out.Add('')
$sources = @(SourceFiles 'src/RnRomManager.Api' '*.cs') + @(SourceFiles 'src/RnRomManager.Core' '*.cs') +
    @(SourceFiles 'src/RnRomManager.Data' '*.cs') + @(SourceFiles 'src/RnRomManager.Web/src/lib' '*.ts', '*.svelte') +
    @(SourceFiles 'src/RnRomManager.Web/static/emulator' '*.js', '*.html', '*.css')
$sources | Where-Object { $_.Name -notmatch '\.test\.ts$' } | Group-Object { Rel $_.DirectoryName } | ForEach-Object {
    $out.Add(('- `{0}/`: {1}' -f $_.Name, (($_.Group | ForEach-Object { $_.Name -replace '\.(cs|ts|svelte|js)$', '' }) -join ', ')))
}

# --- Tests --------------------------------------------------------------------------------------------------------
$out.Add(''); $out.Add('## Tests'); $out.Add('')
$out.Add('.NET: `dotnet test tests/<Project> --filter "FullyQualifiedName~<Class>"`. Integration = Testcontainers (Docker). SPA: `npx vitest run <file>` in src/RnRomManager.Web. E2E: tests/e2e/specs.')
$out.Add('')
Get-ChildItem tests -Directory | Where-Object Name -like 'RnRomManager.*' | Sort-Object Name | ForEach-Object {
    $names = SourceFiles $_.FullName '*Tests.cs' | ForEach-Object { $_.BaseName }
    if ($names) { $out.Add(('- `{0}`: {1}' -f $_.Name, ($names -join ', '))) }
}
$out.Add(('- SPA (`*.test.ts`): {0}' -f ((SourceFiles 'src/RnRomManager.Web/src' '*.test.ts' |
    ForEach-Object { [IO.Path]::GetRelativePath((Resolve-Path 'src/RnRomManager.Web/src'), $_.FullName).Replace('\', '/') }) -join ', ')))
$out.Add(('- E2E: {0}' -f ((SourceFiles 'tests/e2e' '*.spec.ts' | ForEach-Object { Rel $_.FullName }) -join ', ')))

# --- Doc sections -------------------------------------------------------------------------------------------------
$out.Add(''); $out.Add('## Doc sections'); $out.Add('')
$out.Add('Read a section with offset/limit instead of the whole doc (`features.md` alone is ~45k tokens).')
foreach ($doc in @(Get-ChildItem docs -Filter *.md | Where-Object Name -notin 'codemap.md', 'recipes.md' | Sort-Object Name) + @(Get-Item README.md, CONTRIBUTING.md)) {
    $heads = Select-String -Path $doc.FullName -Pattern '^(##|###) (.+)$' | ForEach-Object { '{0} :{1}' -f $_.Matches[0].Groups[2].Value, $_.LineNumber }
    $out.Add('')
    $out.Add(('- `{0}` ({1} lines): {2}' -f (Rel $doc.FullName), (Get-Content $doc.FullName).Count, ($heads -join '; ')))
}

$out.Add('')
[IO.File]::WriteAllLines((Join-Path $root 'docs/codemap.md'), $out)
Write-Host "docs/codemap.md: $($out.Count) lines, $((Get-Item docs/codemap.md).Length) bytes"
